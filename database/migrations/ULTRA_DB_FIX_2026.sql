-- Recreate QR trigger safely (AFTER INSERT so player_id exists)
CREATE OR REPLACE FUNCTION fn_generate_player_qr()
RETURNS TRIGGER AS $$
BEGIN
  UPDATE public.players 
  SET qr_code = LPAD(NEW.player_id::text, 5, '0') || 
                COALESCE(replace(NEW.birth_date::text, '-', ''), '00000000')
  WHERE player_id = NEW.player_id AND qr_code IS NULL;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tr_generate_qr
AFTER INSERT ON public.players
FOR EACH ROW
EXECUTE FUNCTION fn_generate_player_qr();

-- Recreate notify_absence with CORRECT column (parent_id not id)
CREATE OR REPLACE FUNCTION fn_notify_absence()
RETURNS TRIGGER AS $$
DECLARE
  v_player_name TEXT;
  v_parent_id BIGINT;
BEGIN
  IF NEW.status = 'غائب' THEN
    SELECT pl.name, par.parent_id 
    INTO v_player_name, v_parent_id
    FROM public.players pl
    LEFT JOIN public.parents par 
      ON (pl.parent_username = par.username OR pl.phone = par.phone)
    WHERE pl.player_id = NEW.player_id;

    IF v_parent_id IS NOT NULL THEN
      INSERT INTO public.academy_notifications (recipient_role, recipient_id, title, message)
      VALUES ('parent', v_parent_id, '⚠️ غياب اللاعب',
        'نحيطكم علماً بأن اللاعب ' || COALESCE(v_player_name,'') || 
        ' غائب عن حصة التدريب بتاريخ ' || CURRENT_DATE);
    END IF;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tr_notify_absence
AFTER INSERT OR UPDATE ON public.attendance
FOR EACH ROW
EXECUTE FUNCTION fn_notify_absence();

