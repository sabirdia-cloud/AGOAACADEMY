-- 1. Create the parent_notifications table
CREATE TABLE IF NOT EXISTS public.parent_notifications (
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id BIGINT NOT NULL,
    player_id BIGINT, -- Optional: If the notification is about a specific player (attendance, match)
    title TEXT NOT NULL,
    message TEXT NOT NULL,
    type TEXT DEFAULT 'عام', -- Can be 'عام', 'حضور', 'مباراة', 'دفع' (General, Attendance, Match, Payment)
    is_read BOOLEAN DEFAULT false,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    
    -- We assume parent_id might just link to the parents table if it exists, 
    -- but since parents sign in with username/phone, some parents might not have a formal parent_id linked to all players.
    -- To be safe and flexible, parent_id can be a BIGINT (if using parents table), 
    -- or we use parent_identifier (username/phone) as TEXT.
    -- Since the current system uses both `parents` table and `player.parent_username`, we'll add identifier too.
    parent_identifier TEXT
);

-- 2. Enable RLS
ALTER TABLE public.parent_notifications ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Allow All" ON public.parent_notifications;
CREATE POLICY "Allow All" ON public.parent_notifications FOR ALL USING (true) WITH CHECK (true);

-- 3. Reload Schema
NOTIFY pgrst, 'reload schema';

-- For safety, update existing table if columns are missing
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'parent_notifications' AND column_name = 'parent_identifier') THEN
        ALTER TABLE public.parent_notifications ADD COLUMN parent_identifier TEXT;
    END IF;
END $$;
