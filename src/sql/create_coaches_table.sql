-- Create coaches table
create table if not exists public.coaches (
  coach_id bigint generated by default as identity primary key,
  name text not null,
  phone text,
  email text,
  license text,
  team_id bigint, -- Optional: if a coach is assigned to a specific team directly
  username text,
  password text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Enable RLS
alter table public.coaches enable row level security;

-- Create permissive policy for demo
create policy "Enable all access for anon" on public.coaches for all using (true) with check (true);

