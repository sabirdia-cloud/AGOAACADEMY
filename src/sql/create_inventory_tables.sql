-- Create products table
create table if not exists public.products (
  product_id bigint generated by default as identity primary key,
  name text not null unique,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Create stock_entries table
create table if not exists public.stock_entries (
  entry_id bigint generated by default as identity primary key,
  receipt_number text not null,
  entry_date date not null,
  product_name text not null,
  quantity integer not null check (quantity > 0),
  purchase_date date,
  source text,
  notes text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Create stock_outputs table
create table if not exists public.stock_outputs (
  output_id bigint generated by default as identity primary key,
  receipt_number text not null,
  output_date date not null,
  product_name text not null,
  quantity integer not null check (quantity > 0),
  beneficiary text,
  notes text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Enable RLS
alter table public.products enable row level security;
alter table public.stock_entries enable row level security;
alter table public.stock_outputs enable row level security;

-- Create permissive policies for demo
create policy "Enable all access for anon" on public.products for all using (true) with check (true);
create policy "Enable all access for anon" on public.stock_entries for all using (true) with check (true);
create policy "Enable all access for anon" on public.stock_outputs for all using (true) with check (true);
