-- Create match_squads table to store selected players for each match
create table if not exists public.match_squads (
  id bigint generated by default as identity primary key,
  match_id bigint references public.matches(match_id) on delete cascade not null,
  player_id bigint references public.players(player_id) on delete cascade not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  unique(match_id, player_id)
);

-- Add RLS policies if RLS is enabled (optional but recommended)
alter table public.match_squads enable row level security;

create policy "Enable read access for all users" on public.match_squads
  for select using (true);

create policy "Enable insert for authenticated users only" on public.match_squads
  for insert with check (auth.role() = 'authenticated');

create policy "Enable delete for authenticated users only" on public.match_squads
  for delete using (auth.role() = 'authenticated');
