CREATE TABLE IF NOT EXISTS player_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  player_id BIGINT REFERENCES players(player_id) ON DELETE CASCADE,
  message TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- RLS
ALTER TABLE player_messages ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow all to admin for player_messages" ON player_messages FOR ALL USING (true);
CREATE POLICY "Allow select to parent for player_messages" ON player_messages FOR SELECT USING (true);
