-- Create academy_settings table
create table if not exists public.academy_settings (
  id bigint generated by default as identity primary key,
  name text,
  logo_url text,
  address text,
  phone text,
  email text,
  website text,
  description text,
  print_logo boolean default true,
  print_qr boolean default true,
  print_color text default 'color',
  print_size text default 'A4',
  language text default 'ar',
  currency text default 'DZD',
  date_format text default 'DD/MM/YYYY',
  notifications_enabled boolean default true,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Ensure only one row exists for settings
create unique index if not exists one_row_only_uidx on public.academy_settings ((true));

