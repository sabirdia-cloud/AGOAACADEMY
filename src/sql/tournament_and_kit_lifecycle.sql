-- Tournament Builder and Kit Life-cycle SQL Migration
-- Features: Tournament Management, Brackets, Group Standings, and Player Kit Lifecycle tracking.

-- 1. TOURNAMENTS TABLE
CREATE TABLE IF NOT EXISTS ems_tournaments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    season TEXT,
    type TEXT DEFAULT 'league', -- 'league', 'groups', 'knockout'
    status TEXT DEFAULT 'active', -- 'active', 'finished'
    description TEXT,
    start_date DATE,
    end_date DATE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. TOURNAMENT TEAMS (Mapping)
CREATE TABLE IF NOT EXISTS ems_tournament_teams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id BIGINT REFERENCES ems_tournaments(id) ON DELETE CASCADE,
    team_id BIGINT, -- references teams.id
    group_name TEXT, -- 'A', 'B', 'C', 'D' for 'groups' type
    points INTEGER DEFAULT 0,
    played INTEGER DEFAULT 0,
    won INTEGER DEFAULT 0,
    drawn INTEGER DEFAULT 0,
    lost INTEGER DEFAULT 0,
    gf INTEGER DEFAULT 0, -- Goals For
    ga INTEGER DEFAULT 0, -- Goals Against
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. TOURNAMENT MATCHES
CREATE TABLE IF NOT EXISTS ems_tournament_matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id BIGINT REFERENCES ems_tournaments(id) ON DELETE CASCADE,
    home_team_id BIGINT,
    away_team_id BIGINT,
    match_date TIMESTAMP WITH TIME ZONE,
    home_score INTEGER DEFAULT 0,
    away_score INTEGER DEFAULT 0,
    status TEXT DEFAULT 'scheduled', -- 'scheduled', 'played', 'cancelled'
    group_name TEXT,
    round TEXT, -- 'Round of 16', 'Quarter-final', 'Semi-final', 'Final'
    pitch TEXT,
    referee TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. PLAYER KIT LIFECYCLE TRACKING
CREATE TABLE IF NOT EXISTS ems_player_kit_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id BIGINT NOT NULL,
    item_type TEXT NOT NULL, -- 'Suit', 'Jersey', 'Shorts', 'Socks', 'Bag'
    size TEXT,
    kit_number TEXT,
    status TEXT DEFAULT 'issued', -- 'issued', 'returned', 'lost', 'damaged'
    distributed_at DATE DEFAULT CURRENT_DATE,
    returned_at DATE,
    notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

