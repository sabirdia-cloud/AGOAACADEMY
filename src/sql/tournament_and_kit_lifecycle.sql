ALTER TABLE ems_tournaments ENABLE ROW LEVEL SECURITY;
ALTER TABLE ems_tournament_teams ENABLE ROW LEVEL SECURITY;
ALTER TABLE ems_tournament_matches ENABLE ROW LEVEL SECURITY;
ALTER TABLE ems_player_kit_assignments ENABLE ROW LEVEL SECURITY;

