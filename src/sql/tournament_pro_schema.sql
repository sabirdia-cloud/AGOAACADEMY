-- Tournament Generator Pro (Standalone Module)
-- Prefix: tg_
-- This schema is independent of the main academy tables.

-- 1. TEAMS
CREATE TABLE IF NOT EXISTS tg_teams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    academy_type TEXT DEFAULT 'external', -- 'academy', 'external'
    city TEXT,
    logo_url TEXT,
    internal_team_id BIGINT, -- Optional link to main academy teams if needed
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. GROUPS
CREATE TABLE IF NOT EXISTS tg_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL, -- 'Group A', 'Group B'...
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. GROUP TEAMS (Mapping)
CREATE TABLE IF NOT EXISTS tg_group_teams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT REFERENCES tg_groups(id) ON DELETE CASCADE,
    team_id BIGINT REFERENCES tg_teams(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    UNIQUE(group_id, team_id)
);

-- 4. MATCHES
CREATE TABLE IF NOT EXISTS tg_matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT REFERENCES tg_groups(id) ON DELETE CASCADE,
    team1_id BIGINT REFERENCES tg_teams(id) ON DELETE CASCADE,
    team2_id BIGINT REFERENCES tg_teams(id) ON DELETE CASCADE,
    match_date DATE,
    match_time TIME,
    team1_score INTEGER DEFAULT 0,
    team2_score INTEGER DEFAULT 0,
    status TEXT DEFAULT 'pending', -- 'pending', 'finished'
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- RLS POLICIES
ALTER TABLE tg_teams ENABLE ROW LEVEL SECURITY;
ALTER TABLE tg_groups ENABLE ROW LEVEL SECURITY;
ALTER TABLE tg_group_teams ENABLE ROW LEVEL SECURITY;
ALTER TABLE tg_matches ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Public Access tg_teams" ON tg_teams FOR ALL USING (true);
CREATE POLICY "Public Access tg_groups" ON tg_groups FOR ALL USING (true);
CREATE POLICY "Public Access tg_group_teams" ON tg_group_teams FOR ALL USING (true);
CREATE POLICY "Public Access tg_matches" ON tg_matches FOR ALL USING (true);
